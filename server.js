const express = require('express');
const path = require('path');
const app = express();
app.use(express.json({limit:'100mb'}));
app.get('/api/productos', (req,res)=>res.json([]));
app.post('/api/productos', (req,res)=>res.json({ok:true}));
app.delete('/api/productos/:id', (req,res)=>res.json({ok:true}));
app.get('/api/banners', (req,res)=>res.json([]));
app.post('/api/banners', (req,res)=>res.json({ok:true}));
app.delete('/api/banners/:id', (req,res)=>res.json({ok:true}));
app.use(express.static(__dirname));
app.get('/admin.html', (req,res)=>res.sendFile(path.join(__dirname,'admin.html')));
app.get('*', (req,res)=>res.sendFile(path.join(__dirname, req.path==='/'?'index.html':req.path), (e)=>{if(e) res.sendFile(path.join(__dirname,'admin.html'));}));
const PORT = process.env.PORT || 10000;
app.listen(PORT, ()=>console.log('ON '+PORT));
